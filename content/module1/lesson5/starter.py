import pandas as pd

df = pd.read_csv('/data/churn_ru.csv')

# Инсайт 1: разница оттока по типу договора
by_contract = df.groupby('тип_договора')['отток'].mean()
print(f"1. Инсайт: отток у безсрочного договора {by_contract['Безсрочный']:.2%}, "
      f"у двухлетнего {by_contract['2 года']:.2%}")

# Инсайт 2: разница по стажу
short = df[df['стаж_месяцев'] < 6]['отток'].mean()
long = df[df['стаж_месяцев'] > 24]['отток'].mean()
print(f"2. Инсайт: отток новичков {short:.2%}, старожилов {long:.2%}")

# Инсайт 3: влияние жалоб
no_comp = df[df['жалобы_12мес'] == 0]['отток'].mean()
many_comp = df[df['жалобы_12мес'] >= 3]['отток'].mean()
print(f"3. Инсайт: отток без жалоб {no_comp:.2%}, с 3+ жалобами {many_comp:.2%}")

# Инсайт 4: влияние просрочек
no_delay = df[df['просрочки_платежей_12мес'] == 0]['отток'].mean()
many_del = df[df['просрочки_платежей_12мес'] >= 3]['отток'].mean()
print(f"4. Инсайт: отток без просрочек {no_delay:.2%}, с 3+ просрочками {many_del:.2%}")

